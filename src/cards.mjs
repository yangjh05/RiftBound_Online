export function getDecklist(id) {
  return decklists[id];
}

function resolveDecklist(deck) {
  return {
    ...deck,
    legend: cardByNumber(deck.legend),
    battlefields: deck.battlefields.map(cardByNumber),
    runes: deck.runes.flatMap(([domain, count]) => copies(makeRune(domain), count)),
    main: deckCards(deck.main),
    sideboard: deckCards(deck.sideboard || [])
  };
}

function deckCards(entries) {
  return entries.flatMap(([cardNumber, count]) => copies(cardByNumber(cardNumber), count));
}

function copies(item, count) {
  return Array.from({ length: count }, () => item);
}

function assertUniqueCardNumbers(cardMap) {
  const seen = new Map();
  for (const [key, card] of Object.entries(cardMap)) {
    if (!card.cardNumber) {
      throw new Error(`Card ${key} (${card.name}) is missing a unique cardNumber.`);
    }
    const previous = seen.get(card.cardNumber);
    if (previous) {
      throw new Error(`Duplicate cardNumber ${card.cardNumber}: ${previous.key} (${previous.name}) and ${key} (${card.name}).`);
    }
    seen.set(card.cardNumber, { key, name: card.name });
  }
}


