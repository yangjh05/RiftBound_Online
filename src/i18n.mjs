export function normalizeLocale(locale) {
  return locale === LOCALES.KO ? LOCALES.KO : LOCALES.EN;
}

export function t(key, locale = LOCALES.EN, params = {}) {
  const table = locale === LOCALES.KO ? UI_KO : UI_EN;
  const value = table[key] || key;
  return String(value).replace(/\{(\w+)\}/gu, (_, name) => params[name] ?? "");
}

export function translateType(type, locale = LOCALES.EN) {
  if (locale !== LOCALES.KO) return type;
  return TYPE_TRANSLATIONS[type] || markUnconfirmed(type);
}

export function translateDomain(domain, locale = LOCALES.EN) {
  if (locale !== LOCALES.KO) return domain;
  return DOMAIN_TRANSLATIONS[domain] || markUnconfirmed(domain);
}

export function translateKeyword(keyword, locale = LOCALES.EN) {
  if (locale !== LOCALES.KO) return keyword;
  const entry = KEYWORD_TRANSLATIONS[keyword];
  if (!entry) return markUnconfirmed(keyword);
  return entry.confirmed ? entry.ko : markUnconfirmed(entry.ko);
}

export function translateKeywordList(keywords = [], locale = LOCALES.EN) {
  return keywords.map((keyword) => translateKeyword(keyword, locale));
}

export function translateCardName(card, locale = LOCALES.EN) {
  if (locale !== LOCALES.KO) return card?.name || "";
  if (card?.type === "rune") return `${translateDomain(card.domain || card.domains?.[0] || "Any", locale)} 룬`;
  return cardKo(card)?.koName || card?.translations?.ko?.name || card?.name || "";
}

export function translateCardText(cardOrText, locale = LOCALES.EN) {
  const card = typeof cardOrText === "string" ? null : cardOrText;
  const text = typeof cardOrText === "string" ? cardOrText : cardOrText?.translations?.ko?.text || cardOrText?.text || "";
  if (locale !== LOCALES.KO || !text) return text;
  const translated = cardKo(card)?.koText || `공식 번역 미확인\n${text}`;
  return normalizeKoreanCardTerminology(translated);
}

export function normalizeKoreanCardTerminology(text = "") {
  return String(text)
    .replace(/매복/gu, "기습")
    .replace(/탭:/gu, "탈진:")
    .replace(/버림 더미|무덤/gu, "폐기장")
    .replace(/공격력/gu, "위력")
    .replace(/체력치/gu, "체력");
}

export function translateCardTags(card, locale = LOCALES.EN) {
  if (locale !== LOCALES.KO) return [card.type, ...(card.tags || [])].filter(Boolean);
  const translated = cardKo(card)?.koTypeLine;
  if (translated) return translated.split(/\s*,\s*/u).filter(Boolean);
  return [translateType(card.type, locale), ...(card.tags || []).map((tag) => translateKeyword(tag, locale))].filter(Boolean);
}

export function translateCostDomain(domain, locale = LOCALES.EN, card = null) {
  if (locale !== LOCALES.KO) return domain;
  if (domain === "Any" && card?.domains?.length) {
    return card.domains.map((cardDomain) => translateDomain(cardDomain, locale)).join("/");
  }
  return translateDomain(domain, locale);
}

export function cardSearchText(card, locale = LOCALES.EN) {
  return [
    card.name,
    translateCardName(card, locale),
    card.type,
    translateType(card.type, locale),
    card.cardNumber,
    card.collectorNumber,
    card.text,
    translateCardText(card, locale),
    ...(card.tags || []),
    ...translateCardTags(card, locale),
    ...(card.keywords || []),
    ...translateKeywordList(card.keywords || [], locale),
    ...(card.domains || []),
    ...(card.domains || []).map((domain) => translateDomain(domain, locale))
  ].join(" ");
}

export function translationMetadata() {
  return {
    keywords: KEYWORD_TRANSLATIONS,
    ui: uiTranslationCoverage()
  };
}

export function uiTranslationCoverage() {
  const koreanKeys = Object.keys(UI_KO);
  const englishKeys = Object.keys(UI_EN);
  return {
    koreanKeys,
    englishKeys,
    missingKorean: englishKeys.filter((key) => !(key in UI_KO)),
    missingEnglish: koreanKeys.filter((key) => !(key in UI_EN))
  };
}

function cardKo(card) {
  if (!card) return null;
  return CARD_KO_TRANSLATIONS[card.cardNumber] || CARD_KO_TRANSLATIONS[card.collectorNumber] || null;
}

function markUnconfirmed(value) {
  return `${value} (미확정)`;
}
