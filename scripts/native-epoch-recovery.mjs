import assert from 'node:assert/strict';
import {tf} from '../src/ai/neural/tf-runtime.mjs';
import {restoreAdamOptimizer} from '../src/ai/neural/trainer.mjs';
import {ACTOR_LAYERS,trainingLossDirections} from './ppo-training-projection.mjs';
import {playOnlyMasks} from './phase-policy-learning.mjs';
import {readAdamGeometry,gradientsForAdamDelta} from './adam-update-geometry.mjs';
import {adamReachableBounds,projectReachableAdamDelta} from './reachable-adam-projection.mjs';

const norm=arrays=>Math.sqrt(arrays.reduce((sum,a)=>sum+a.reduce((s,x)=>s+x*x,0),0));
// All candidate construction uses the saved PPO displacement and training
// gradients. The endpoint is generated by REAL Adam steps before any held-out
// test. No interpolated weight is ever tested/accepted and then assigned an
// unrelated optimizer. Existing full/play-only routes use seven fractions each.
export async function nativeEpochRecovery({model,bank,args,names,steps,measure,learningRate=.0001}){
  assert.ok(Number.isSafeInteger(steps)&&steps>0);
  const variables=Object.values(model.layers).flatMap(l=>l.trainableWeights.map(w=>w.val));
  const indexes=new Map(variables.map((v,i)=>[v.name,i])),raw=variables.map(v=>Float64Array.from(v.dataSync()));
  const reset=()=>{for(const [name,weights]of Object.entries(args.epochStartWeights))model.layers[name].setWeights(weights);};
  reset();const base=variables.map(v=>Float64Array.from(v.dataSync())),delta=raw.map((a,k)=>Float64Array.from(a,(x,i)=>x-base[k][i]));
  const actor=ACTOR_LAYERS.flatMap(n=>model.layers[n].trainableWeights.map(w=>w.val));
  const actorIndexes=new Map(actor.map((v,i)=>[v.name,i]));
  const groups=trainingLossDirections(model,bank);
  const phase=playOnlyMasks(args.epochStartWeights),masks=variables.map(v=>actorIndexes.has(v.name)?phase[actorIndexes.get(v.name)]:new Uint8Array(v.size));
  const attempts=[];let optimizer=null,result=null;
  try{
    for(const route of ['full-policy','play-only-action-rows'])for(const fraction of [1,.5,.25,.125,.0625,.03125,.015625]){
      reset();optimizer=await restoreAdamOptimizer(args.optimizerSnapshot,learningRate);
      const mask=route==='full-policy'?null:masks;
      const target=delta.map((a,k)=>Float64Array.from(a,(x,i)=>!mask||mask[k][i]?x*fraction:0));
      const directions=groups.map(g=>{
        const values=variables.map((v,k)=>actorIndexes.has(v.name)?Float64Array.from(g.values[actorIndexes.get(v.name)],(x,i)=>!mask||mask[k][i]?x:0):new Float64Array(v.size));
        const length=norm(values);return {type:g.type,norm:length,values:values.map(a=>Float64Array.from(a,x=>length?x/length:0))};
      }).filter(g=>g.norm>1e-12);
      let reason=null,applied=0;
      for(let step=0;step<steps;step++){
        const remaining=variables.map((v,k)=>{const actual=v.dataSync();return Float64Array.from(target[k],(x,i)=>(base[k][i]+x-actual[i])/(steps-step));});
        const length=norm(remaining);if(length<=1e-12){reason='no-policy-displacement';break;}
        const geometry=readAdamGeometry(optimizer,names,variables);
        const projection=projectReachableAdamDelta(remaining,directions,adamReachableBounds(names,variables,geometry,learningRate,mask),
          {minimumDescent:.01*length,maximumNorm:2*length});
        if(!projection.feasible){reason='joint-training-adam-constraints-infeasible';break;}
        const inverse=gradientsForAdamDelta(projection.delta,variables.map(v=>new Float64Array(v.size)),names,variables,geometry,learningRate);
        if(!inverse.feasible){reason=inverse.reason;break;}
        const gradients=Object.fromEntries(names.map(name=>{const k=indexes.get(name);return [name,tf.tensor(Float32Array.from(inverse.values[k]),variables[k].shape)];}));
        try{optimizer.applyGradients(gradients);applied++;}finally{Object.values(gradients).forEach(g=>g.dispose());}
      }
      if(!reason){result=measure();attempts.push({route,fraction,steps:applied,passed:result.passed,validation:result.validation,training:result.training,additionalGuard:result.additionalGuard});
        if(result.passed){const accepted=optimizer;optimizer=null;return {passed:true,optimizer:accepted,result,attempts,steps:applied};}}
      else attempts.push({route,fraction,steps:applied,passed:false,reason});
      optimizer.dispose();optimizer=null;
    }
    reset();return {passed:false,attempts,result};
  }finally{optimizer?.dispose();}
}
