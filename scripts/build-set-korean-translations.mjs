import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cards } from "../src/cards.mjs";
import { buildUnofficialCardTranslation } from "../src/cards/koreanEffectSummary.mjs";
import { spiritforgedPrintedTextKo, unleashedPrintedTextKo } from "../src/cards/koreanPrintedText.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = parseArgs(process.argv.slice(2));
const setId = String(args.set || "SFD").toUpperCase();
const setConfig = {
  SFD: {
    names: "spec/cards/spiritforged-ko-names.json",
    output: "src/cards/spiritforgedKoTranslations.mjs",
    exportName: "spiritforgedKoTranslations"
  },
  UNL: {
    names: "spec/cards/unleashed-ko-names.json",
    output: "src/cards/unleashedKoTranslations.mjs",
    exportName: "unleashedKoTranslations"
  },
  VEN: {
    names: "spec/cards/vendetta-ko-names.json",
    text: "spec/cards/vendetta-ko-text.json",
    output: "src/cards/vendettaKoTranslations.mjs",
    exportName: "vendettaKoTranslations"
  }
}[setId];
if (!setConfig) throw new Error(`Unsupported set: ${setId}`);
const namesPath = path.resolve(ROOT, String(args.names || setConfig.names));
const outputPath = path.resolve(ROOT, String(args.output || setConfig.output));
const exportName = String(args.export || setConfig.exportName);
const names = JSON.parse(fs.readFileSync(namesPath, "utf8"));
const printedTextBySet = { SFD: spiritforgedPrintedTextKo, UNL: unleashedPrintedTextKo };
const printedTextKo = setConfig.text
  ? JSON.parse(fs.readFileSync(path.resolve(ROOT, setConfig.text), "utf8"))
  : printedTextBySet[setId] || {};
const setCards = Object.values(cards)
  .filter((card) => String(card.cardNumber || "").startsWith(`${setId}-`))
  .sort((left, right) => left.cardNumber.localeCompare(right.cardNumber, "en", { numeric: true }));
const missingNames = setCards.filter((card) => !names[card.cardNumber]).map((card) => card.cardNumber);
if (missingNames.length) throw new Error(`Missing Korean names: ${missingNames.join(", ")}`);
let translations;
if (setConfig.snapshot) {
  const snapshot = JSON.parse(fs.readFileSync(path.resolve(ROOT, setConfig.snapshot), "utf8"));
  const snapshotCards = snapshot.cards || {};
  const missing = setCards.filter((card) => !snapshotCards[card.cardNumber]).map((card) => card.cardNumber);
  if (missing.length) throw new Error(`Missing Korean snapshot entries: ${missing.join(", ")}`);
  translations = Object.fromEntries(setCards.map((card) => [card.cardNumber, snapshotCards[card.cardNumber]]));
} else {
  const missingText = setCards.filter((card) => card.text && !printedTextKo[card.cardNumber]).map((card) => card.cardNumber);
  if (missingText.length) throw new Error(`Missing Korean printed text: ${missingText.join(", ")}`);
  translations = Object.fromEntries(setCards.map((card) => [
    card.cardNumber,
    buildUnofficialCardTranslation(card, names[card.cardNumber], printedTextKo[card.cardNumber])
  ]));
}
const source = `// Generated by scripts/build-set-korean-translations.mjs.\n// Edit the Korean name source or Korean printed-text map, then regenerate.\nexport const ${exportName} = Object.freeze(${JSON.stringify(translations, null, 2)});\n`;
fs.writeFileSync(outputPath, source, "utf8");
console.log(`Generated ${setCards.length} ${setId} Korean translations in ${path.relative(ROOT, outputPath)}.`);

function parseArgs(values) {
  const parsed = {};
  for (let index = 0; index < values.length; index += 1) {
    const token = values[index];
    if (!token.startsWith("--")) continue;
    const key = token.slice(2);
    const next = values[index + 1];
    parsed[key] = !next || next.startsWith("--") ? true : next;
    if (parsed[key] !== true) index += 1;
  }
  return parsed;
}
