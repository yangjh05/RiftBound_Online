import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const args = parseArgs(process.argv.slice(2));
const setId = String(args.set || "UNL").toUpperCase();
const setConfig = {
  UNL: { slug: "unleashed", exportName: "unleashedCards", registryPrefix: "unl", total: 219 },
  VEN: { slug: "vendetta", exportName: "vendettaCards", registryPrefix: "ven", total: 166 }
}[setId];
if (!setConfig) throw new Error(`Unsupported generated set: ${setId}`);
const sourcePath = path.resolve(ROOT, String(args.source || `spec/cards/${setConfig.slug}-official-2026-08-29.json`));
const implementationPath = path.resolve(ROOT, String(args.implementations || `spec/cards/${setConfig.slug}-effects.json`));
const contractsPath = path.resolve(ROOT, "spec/cards/card-behavior-contracts.json");
const outputPath = path.resolve(ROOT, String(args.output || `src/cards/${setConfig.slug}Cards.mjs`));

const snapshot = readJson(sourcePath);
const implementationSpec = readJson(implementationPath);
const contracts = readJson(contractsPath).cards || [];
const manualCardNumbers = new Set(implementationSpec.manualCardNumbers || []);
const references = buildReferenceIndex(contracts);
const overrides = implementationSpec.cards || {};

const officialNumbers = new Set(snapshot.cards.map((card) => card.cardNumber));
const missingOverrideNumbers = Object.keys(overrides).filter((cardNumber) => !officialNumbers.has(cardNumber));
const missingManualNumbers = [...manualCardNumbers].filter((cardNumber) => !officialNumbers.has(cardNumber));
if (missingOverrideNumbers.length || missingManualNumbers.length) {
  throw new Error([
    missingOverrideNumbers.length ? `Implementation entries do not exist in the official snapshot: ${missingOverrideNumbers.join(", ")}` : "",
    missingManualNumbers.length ? `Manual entries do not exist in the official snapshot: ${missingManualNumbers.join(", ")}` : ""
  ].filter(Boolean).join("\n"));
}

const generated = snapshot.cards
  .filter((card) => !manualCardNumbers.has(card.cardNumber))
  .map((sourceCard) => buildCard(sourceCard, overrides[sourceCard.cardNumber] || {}, references));

const source = `// Generated by scripts/build-unleashed-cards.mjs. Edit the official snapshot or
// spec/cards/${setConfig.slug}-effects.json, then regenerate this module.
import { card } from "./shared.mjs";

const definitions = ${JSON.stringify(generated, null, 2)};

export const ${setConfig.exportName} = Object.fromEntries(
  definitions.map((definition) => [definition.registryKey, card(definition.card)])
);
`;

fs.writeFileSync(outputPath, source, "utf8");
console.log(`Generated ${generated.length} Unleashed cards in ${path.relative(ROOT, outputPath)}.`);
console.log(`Effect declarations: ${generated.reduce((sum, entry) => sum + entry.card.effects.length, 0)}.`);

function buildCard(sourceCard, override, referencesByEffect) {
  const effectiveKeywords = [...new Set([
    ...(sourceCard.keywords || []),
    ...(override.keywords || []),
    ...(hasPrintedKeyword(sourceCard, "Equip") ? ["Equip"] : [])
  ])];
  const normalizedSourceCard = { ...sourceCard, keywords: effectiveKeywords };
  const authoredEffects = structuredClone(override.effects || []);
  const authoredEffectKeys = new Set(authoredEffects.map(effectKey));
  const effects = [
    ...deriveCoreEffects(normalizedSourceCard).filter((effect) => !authoredEffectKeys.has(effectKey(effect))),
    ...authoredEffects
  ];
  const grantedTags = effects
    .filter((effect) => effect.timing === "static" && effect.kind === "gainTags")
    .flatMap((effect) => effect.tags || []);
  applyRepeatCost(sourceCard, effects);
  if (sourceCard.mightBonus != null && !effects.some((effect) => effect.timing === "static" && effect.kind === "attachedMight")) {
    effects.push({ timing: "static", kind: "attachedMight", textSection: "mightBonus", amount: sourceCard.mightBonus });
  }
  const explicitReferences = override.implementationReferences || {};
  const implementationReferences = {};
  for (const effect of effects) {
    const key = effectKey(effect);
    const automaticReference = referencesByEffect.get(`${sourceCard.type}:${key}`);
    const reference = explicitReferences[key]
      || (automaticReference !== sourceCard.cardNumber ? automaticReference : null);
    if (reference) implementationReferences[key] = reference;
  }
  const attachedEffectText = meaningfulAttachedEffectText(sourceCard.effectText);
  const combinedText = [sourceCard.effectiveText, attachedEffectText].filter(Boolean).join("\n");
  return {
    registryKey: override.registryKey || `${setConfig.registryPrefix}${sourceCard.id.slice(4)}${camelCase(sourceCard.name)}`,
    card: {
      id: sourceCard.id,
      collectorNumber: sourceCard.collectorNumber,
      name: sourceCard.name,
      type: sourceCard.type,
      ...(sourceCard.types?.length ? { types: sourceCard.types } : {}),
      set: sourceCard.set,
      rarity: sourceCard.rarity,
      domains: sourceCard.domains,
      tags: [...new Set([...sourceCard.tags, ...grantedTags])],
      keywords: effectiveKeywords,
      ...(sourceCard.isChampion ? { isChampion: true } : {}),
      ...(sourceCard.energy != null ? { energy: sourceCard.energy } : {}),
      power: sourceCard.power,
      ...(sourceCard.might != null ? { might: sourceCard.might } : {}),
      image: sourceCard.image,
      text: combinedText,
      ...(override.additionalCost ? { additionalCost: normalizeAdditionalCost(override.additionalCost) } : {}),
      ...(Object.keys(implementationReferences).length ? { implementationReferences } : {}),
      effects
    }
  };
}

function normalizeAdditionalCost(cost) {
  if (cost.optionalDiscard) {
    return { kind: "optionalDiscardEnergyReduction", amount: cost.optionalDiscard, energyReduction: 0 };
  }
  if (cost.optionalEnergy) {
    return { kind: "optionalEnergy", amount: cost.optionalEnergy };
  }
  if (cost.optionalPower?.length) {
    const requirement = cost.optionalPower[0];
    return { kind: "optionalPower", domain: requirement.domain || "Any", amount: requirement.amount || 1 };
  }
  return structuredClone(cost);
}

function deriveCoreEffects(sourceCard) {
  const effects = [];
  if (sourceCard.keywords.includes("Equip")) effects.push(deriveEquipEffect(sourceCard));
  if (/(?:^|\n)(?:This enters|I enter) exhausted\.|\(I enter exhausted\.\)/i.test(sourceCard.effectiveText || "")) {
    effects.push({ timing: "static", kind: "entersExhausted" });
  }
  const empowerLine = String(sourceCard.effectiveText || "").split("\n")
    .find((entry) => entry.trim().startsWith("[Empower]") && /Empower (?:me|this)\b/i.test(entry));
  if (empowerLine) effects.push(deriveEmpowerEffect(sourceCard, empowerLine));
  const flowLine = String(sourceCard.effectiveText || "").split("\n")
    .find((entry) => entry.trim().startsWith("[Flow]"));
  if (flowLine) effects.push(...deriveFlowEffects(sourceCard, flowLine));
  return effects;
}

function deriveEmpowerEffect(sourceCard, line) {
  // Printed reminder/condition prose can share the same physical line. Only the
  // declarative cost before the first sentence boundary belongs to Empower.
  const costText = line.replace(/^\s*\[Empower\]\s*(?:—\s*)?/, "").split("(")[0].split(".")[0].trim();
  const parsed = parsePrintedCost(costText);
  return {
    timing: "activated",
    kind: "empowerSelf",
    abilityId: "empower",
    exhaust: /\bExhaust\b/i.test(costText),
    onlyIfNotEmpowered: !/up to three times/i.test(sourceCard.effectiveText || ""),
    ...(/up to three times/i.test(sourceCard.effectiveText || "") ? { maxEmpowerCount: 3 } : {}),
    ...(parsed.alternatives?.length ? { costOptions: parsed.alternatives } : {}),
    ...(!parsed.alternatives?.length && parsed.energy ? { costEnergy: parsed.energy } : {}),
    ...(!parsed.alternatives?.length && parsed.power.length ? { costPower: parsed.power } : {}),
    ...(/\bDiscard\s+(?:1|a spell)\b/i.test(costText) ? { costDiscard: 1 } : {}),
    ...(/\bDiscard\s+a spell\b/i.test(costText) ? { costDiscardType: "spell" } : {}),
    ...(/Kill a friendly unit/i.test(costText) ? { killFriendlyUnitCost: true } : {})
  };
}

function deriveFlowEffects(sourceCard, line) {
  const costText = line.replace(/^\s*\[Flow\]\s*(?:—\s*)?/, "").split("(")[0].trim();
  const parsed = parsePrintedCost(costText);
  return [
    {
      timing: "static",
      kind: "playSelfFromTrash",
      flow: true,
      replacementEnergy: parsed.energy,
      replacementPower: parsed.power
    },
    { timing: "spell", kind: "banishSelfAfterResolve", flow: true }
  ];
}

function parsePrintedCost(costText) {
  const normalizedCostText = String(costText)
    .replace(/Power(?=(?:Body|Calm|Chaos|Fury|Mind|Order)\s+Power)/g, "Power ")
    .replace(/\s+/g, " ")
    .trim();
  const alternatives = normalizedCostText.split(/\s+or\s+/i);
  if (alternatives.length > 1) {
    return {
      energy: 0,
      power: [],
      alternatives: alternatives.map((part) => {
        const parsed = parsePrintedCost(part);
        return { energy: parsed.energy, power: parsed.power };
      })
    };
  }
  const energy = Number(normalizedCostText.match(/\bEnergy\s+(\d+)\b/i)?.[1] || 0);
  const domains = ["Body", "Calm", "Chaos", "Fury", "Mind", "Order"];
  const power = [];
  let remainder = normalizedCostText;
  for (const domain of domains) {
    const expression = new RegExp(`\\b${domain} Power\\b`, "gi");
    const amount = [...remainder.matchAll(expression)].length;
    if (amount) {
      power.push({ domain, amount });
      remainder = remainder.replace(expression, " ");
    }
  }
  const any = [...remainder.matchAll(/\bPower\b/gi)].length;
  if (any) power.push({ domain: "Any", amount: any });
  return { energy, power };
}

function meaningfulAttachedEffectText(value) {
  const text = String(value || "").trim();
  return /[A-Za-z]/.test(text) ? text : "";
}

function deriveEquipEffect(sourceCard) {
  const line = sourceCard.printedText.split("\n").find((entry) => /^\s*(?:\[Equip\]|Equip)(?:\s|$)/.test(entry));
  if (!line) throw new Error(`${sourceCard.cardNumber} declares Equip without an Equip line.`);
  const costText = line.replace(/^\s*(?:\[Equip\]|Equip)\s*(?:—\s*)?/, "").split("(")[0].trim();
  const domainMatch = costText.match(/\b(Body|Calm|Chaos|Fury|Mind|Order) Power\b/);
  const anyPowerCount = domainMatch ? 0 : (costText.match(/\bPower\b/g) || []).length;
  const effect = {
    timing: "activated",
    kind: "equip",
    abilityId: "equip",
    exhaust: false,
    domain: domainMatch?.[1] || "Any",
    amount: domainMatch ? 1 : Math.max(0, anyPowerCount)
  };
  const energy = Number(costText.match(/\bEnergy\s+(\d+)\b/)?.[1] || 0);
  const xp = Number(costText.match(/\bSpend\s+(\d+)\s+XP\b/i)?.[1] || 0);
  const recycleTrash = Number(costText.match(/\bRecycle\s+(\d+)\s+cards? from your trash\b/i)?.[1] || 0);
  if (energy) effect.costEnergy = energy;
  if (xp) effect.costXp = xp;
  if (recycleTrash) effect.costRecycleTrash = recycleTrash;
  if (/\bKill a friendly unit\b/i.test(costText)) effect.killFriendlyUnitCost = true;
  if (/Energy cost is reduced by the Might of the unit you choose/i.test(line)) {
    effect.energyReducedByTargetMight = true;
  }
  return effect;
}

function hasPrintedKeyword(sourceCard, keyword) {
  return String(sourceCard.printedText || "")
    .split("\n")
    .some((entry) => new RegExp(`^\\s*(?:\\[${keyword}\\]|${keyword})(?:\\s|$)`, "i").test(entry));
}

function applyRepeatCost(sourceCard, effects) {
  if (!sourceCard.keywords.includes("Repeat")) return;
  const repeatedEffects = effects.filter((effect) => effect.timing === "spell");
  if (!repeatedEffects.length) return;
  if (repeatedEffects.length !== 1) {
    throw new Error(`${sourceCard.cardNumber} Repeat must be represented by one repeatable spell resolver.`);
  }
  const line = sourceCard.printedText.split("\n").find((entry) => entry.trim().startsWith("[Repeat]"));
  if (!line) throw new Error(`${sourceCard.cardNumber} declares Repeat without a Repeat line.`);
  if (repeatedEffects[0].repeatCosts) return;
  const costText = line.replace(/^\s*\[Repeat\]\s*(?:—\s*)?/, "").split("(")[0].trim();
  const domainMatch = costText.match(/\b(Body|Calm|Chaos|Fury|Mind|Order) Power\b/);
  const anyPowerCount = domainMatch ? 0 : (costText.match(/\bPower\b/g) || []).length;
  const power = domainMatch
    ? [{ domain: domainMatch[1], amount: 1 }]
    : anyPowerCount ? [{ domain: "Any", amount: anyPowerCount }] : [];
  repeatedEffects[0].repeatCost = {
    energy: Number(costText.match(/\bEnergy\s+(\d+)\b/)?.[1] || 0),
    power,
    discard: Number(costText.match(/\bDiscard\s+(\d+)\b/i)?.[1] || 0)
  };
}

function buildReferenceIndex(contractCards) {
  const index = new Map();
  for (const cardContract of contractCards) {
    for (const effect of cardContract.effects || []) {
      const key = `${cardContract.type}:${effectKey(effect)}`;
      if (!index.has(key)) index.set(key, cardContract.cardNumber);
    }
  }
  return index;
}

function effectKey(effect) {
  return `${effect.timing}:${effect.kind}`;
}

function camelCase(value) {
  const words = String(value).replace(/['’!]/g, "").split(/[^A-Za-z0-9]+/).filter(Boolean);
  return words.map((word, index) => {
    const lower = word.charAt(0).toLowerCase() + word.slice(1);
    return index ? `${lower.charAt(0).toUpperCase()}${lower.slice(1)}` : lower;
  }).join("");
}

function parseArgs(values) {
  const parsed = {};
  for (let index = 0; index < values.length; index += 1) {
    const token = values[index];
    if (!token.startsWith("--")) continue;
    const key = token.slice(2);
    const next = values[index + 1];
    parsed[key] = !next || next.startsWith("--") ? true : next;
    if (parsed[key] !== true) index += 1;
  }
  return parsed;
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}
